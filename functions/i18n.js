/**
 * 创建翻译函数
 * @param {string} lang 'zh' | 'en'
 * @param {Object} overrides 来自数据库的覆盖字典 { key: 'value' }
 */
export function makeT(lang, overrides = {}) {
  return function (key, ...args) {
    let val;
    if (overrides && Object.prototype.hasOwnProperty.call(overrides, key)) {
      val = overrides[key];
    } else if (T[key]) {
      val = T[key][lang] || T[key].zh;
    } else {
      return key;
    }
    if (args.length) {
      args.forEach((a) => { val = String(val).replace('%s', a); });
    }
    return val;
  };
}

