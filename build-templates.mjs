/**
 * 构建脚本：把 views/*.ejs 与 views/partials/*.ejs 预编译为 functions/templates.cjs
 * --------------------------------------------------------------------------
 * 为什么这样做：Cloudflare Workers 禁止运行时「从字符串生成代码」(new Function / eval)，
 * 且 esbuild 把 Worker 统一编译为 ESM 严格模式 —— 连 `with` 语句也不允许。
 * 原先 ejs.render() 在运行时编译模板（用 new Function / with）会双双失败。
 *
 * 本脚本在「构建期」(本地 Node) 把每个模板：
 *   1) 内联 partials（head / foot），产品卡片 include → renderCard(p)
 *   2) 扫描模板用到的变量名，作为 ejs 的 destructuredLocals
 *   3) 用 _with:false + destructuredLocals 编译成「无 with、无 new Function」的真实函数体
 *   4) 直接以函数形式写进 templates.cjs（CommonJS，运行时只调用函数，不再编译）
 *
 * 运行：node build-templates.mjs   （部署前必跑；CI 中放在构建步骤）
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ejs from 'ejs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const VIEWS = path.join(__dirname, 'views');
const PARTIALS = path.join(VIEWS, 'partials');
const read = (p) => fs.readFileSync(p, 'utf8');

const head = read(path.join(PARTIALS, 'head.ejs'));
const foot = read(path.join(PARTIALS, 'foot.ejs'));
const card = read(path.join(PARTIALS, 'product-card.ejs'));

const FILES = ['home', 'products', 'product', 'about', 'certificates', 'contact', '404'];

// 这些词会出现在模板表达式里，但要么是 JS 关键字、要么是全局对象/内置函数，
// 不能被当成「data 局部变量」去解构（否则会把它 shadow 成 undefined 而报错）。
const RESERVED = new Set([
  'break', 'case', 'catch', 'class', 'const', 'continue', 'debugger', 'default', 'delete',
  'do', 'else', 'export', 'extends', 'finally', 'for', 'function', 'if', 'import', 'in',
  'instanceof', 'new', 'return', 'super', 'switch', 'this', 'throw', 'try', 'typeof', 'var',
  'void', 'while', 'with', 'yield', 'let', 'static', 'enum', 'await', 'of', 'as',
  // 严格模式(ECMAScript 5+ reserved / 模块作用域保留字) 不能作为变量名
  'package', 'protected', 'implements', 'interface', 'private', 'public', 'arguments',
  'undefined', 'null', 'true', 'false', 'NaN', 'Infinity',
]);
const GLOBALS = new Set([
  'encodeURIComponent', 'encodeURI', 'decodeURIComponent', 'decodeURI', 'escape', 'unescape',
  'eval', 'String', 'Number', 'Boolean', 'Math', 'JSON', 'Array', 'Object', 'Date', 'RegExp',
  'Error', 'parseInt', 'parseFloat', 'isNaN', 'isFinite', 'Symbol', 'Map', 'Set', 'Promise',
  'Proxy', 'Reflect', 'BigInt', 'WeakMap', 'WeakSet', 'Float64Array', 'Float32Array',
  'Int32Array', 'Uint8Array', 'Int8Array', 'console', 'document', 'window',
  // ejs 内部保留名
  'locals', '__locals', 'escapeFn', '__output', '__append', 'include', 'rethrow', 'opts', 'data',
]);

/** 从（已内联 partials 的）模板源文中提取所有标识符，过滤掉关键字/全局，作为 destructuredLocals */
function extractLocals(src) {
  const ids = new Set();
  const re = /[A-Za-z_$][A-Za-z0-9_$]*/g;
  let m;
  while ((m = re.exec(src))) {
    const w = m[0];
    if (RESERVED.has(w) || GLOBALS.has(w)) continue;
    ids.add(w);
  }
  return [...ids];
}

function processView(f) {
  let s = read(path.join(VIEWS, f + '.ejs'));
  s = s.replace(/<%-?\s*include\('partials\/head'\)\s*-?%>/g, head);
  s = s.replace(/<%-?\s*include\('partials\/foot'\)\s*-?%>/g, foot);
  s = s.replace(
    /<%-?\s*include\('partials\/product-card',\s*\{[^}]*\}\)\s*-?%>/g,
    '<%- renderCard(p) %>'
  );
  return s;
}

function compileSource(src) {
  const locals = extractLocals(src);
  const t = new ejs.Template(src, {
    _with: false,
    destructuredLocals: locals,
    compileDebug: false,
  });
  t.compile();
  return t.source;
}

const sources = {};
for (const f of FILES) sources[f] = compileSource(processView(f));
const cardSource = compileSource(card);

// 每个模板函数体内自带 escapeFn（等价于 ejs 的 escapeXML），不依赖运行时 ejs
const ESCAPE_FN = `  var escapeFn = function (markup) {
    return String(markup == null ? '' : markup)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  };
  var include = function () { return ''; };
  var rethrow = function (e) { throw e; };`;

function emitFn(name, source) {
  return `function ${name}(locals) {
${ESCAPE_FN}
${source}
}`;
}

const fnDefs = FILES.map((f) => emitFn('__t_' + f, sources[f])).join('\n\n');
const cardDef = emitFn('__t_card', cardSource);

const js = `// AUTO-GENERATED by build-templates.mjs — do not edit by hand.
// 预编译的 EJS 模板（真实 JS 函数，无运行时 new Function、无 with，可在 Cloudflare Workers 运行）。
${fnDefs}

${cardDef}

exports.templates = {
${FILES.map((f) => `  ${f}: __t_${f},`).join('\n')}
};
exports.productCardTemplate = __t_card;
`;

fs.writeFileSync(path.join(__dirname, 'functions', 'templates.cjs'), js);
try { fs.unlinkSync(path.join(__dirname, 'functions', 'templates.js')); } catch (_) {}
console.log('✅ functions/templates.cjs generated (' + FILES.length + ' views + product-card)');
