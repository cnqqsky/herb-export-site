/**
 * 构建脚本：把 views/*.ejs 与 views/partials/*.ejs 编译为 functions/templates.js
 * 目的：Pages Functions 运行时没有文件系统（无法 require 读 .ejs），
 *       所以把 EJS 模板内联为 JS 字符串模块，避免运行时 fs。
 *
 * 处理：
 *  - 内联 <%- include('partials/head') %> / <%- include('partials/foot') %>
 *  - 产品卡片 <%- include('partials/product-card', { p: p }) %> 改为 <%- renderCard(p) %>
 *    （renderCard 由 site.js 在渲染时按当前 locals 闭包提供）
 *
 * 运行：node build-templates.mjs   （部署前必跑；CI 中放在构建步骤）
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const VIEWS = path.join(__dirname, 'views');
const PARTIALS = path.join(VIEWS, 'partials');
const read = (p) => fs.readFileSync(p, 'utf8');

const head = read(path.join(PARTIALS, 'head.ejs'));
const foot = read(path.join(PARTIALS, 'foot.ejs'));
const card = read(path.join(PARTIALS, 'product-card.ejs'));

const FILES = ['home', 'products', 'product', 'about', 'certificates', 'contact', '404'];

const out = {};
for (const f of FILES) {
  let s = read(path.join(VIEWS, f + '.ejs'));
  // 内联无参数 include（head / foot）
  s = s.replace(/<%-?\s*include\('partials\/head'\)\s*-?%>/g, head);
  s = s.replace(/<%-?\s*include\('partials\/foot'\)\s*-?%>/g, foot);
  // 产品卡片：带参 include → 调用 renderCard(p)
  s = s.replace(
    /<%-?\s*include\('partials\/product-card',\s*\{[^}]*\}\)\s*-?%>/g,
    '<%- renderCard(p) %>'
  );
  out[f] = s;
}

const js = `// AUTO-GENERATED by build-templates.mjs — do not edit by hand.
export const templates = {
${FILES.map((f) => `  ${f}: ${JSON.stringify(out[f])},`).join('\n')}
};
export const productCardTemplate = ${JSON.stringify(card)};
`;

fs.writeFileSync(path.join(__dirname, 'functions', 'templates.js'), js);
console.log('✅ functions/templates.js generated (' + FILES.length + ' views + product-card)');
